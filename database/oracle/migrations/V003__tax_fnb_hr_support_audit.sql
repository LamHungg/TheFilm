    discount_amount     NUMBER(18,2) DEFAULT 0 NOT NULL,
    taxable_amount      NUMBER(18,2) NOT NULL,
    tax_amount          NUMBER(18,2) NOT NULL,
    line_total          NUMBER(18,2) NOT NULL,
    CONSTRAINT pk_tax_invoice_line PRIMARY KEY (tax_invoice_line_id),
    CONSTRAINT uq_tax_invoice_line_no UNIQUE (tax_invoice_id, line_no),
    CONSTRAINT fk_tax_line_invoice FOREIGN KEY (tax_invoice_id) REFERENCES tax_invoice (tax_invoice_id),
    CONSTRAINT fk_tax_line_order_line FOREIGN KEY (order_line_id) REFERENCES sales_order_line (order_line_id),
    CONSTRAINT ck_tax_invoice_line_qty CHECK (quantity > 0),
    CONSTRAINT ck_tax_invoice_line_amount CHECK (tax_rate_snapshot >= 0 AND unit_price >= 0 AND discount_amount >= 0 AND taxable_amount >= 0 AND tax_amount >= 0 AND line_total >= 0)
);

