-- THEFILM Oracle schema - V003
-- Simulation-only tax/invoice data, F&B inventory, workforce, customer support and audit/outbox.

CREATE TABLE tax_category (
    tax_category_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_code   VARCHAR2(40 CHAR) NOT NULL,
    category_name   VARCHAR2(150 CHAR) NOT NULL,
    description     VARCHAR2(500 CHAR),
    status          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_tax_category PRIMARY KEY (tax_category_id),
    CONSTRAINT uq_tax_category_code UNIQUE (category_code),
    CONSTRAINT ck_tax_category_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE tax_rule (
    tax_rule_id        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tax_category_id    NUMBER(19) NOT NULL,
    rule_code          VARCHAR2(40 CHAR) NOT NULL,
    tax_name           VARCHAR2(100 CHAR) NOT NULL,
    tax_type           VARCHAR2(20 CHAR) NOT NULL,
    calculation_method VARCHAR2(20 CHAR) NOT NULL,
    rate_percent       NUMBER(7,4) NOT NULL,
    valid_from         TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to           TIMESTAMP WITH TIME ZONE,
    source_reference   VARCHAR2(500 CHAR),
    simulation_only    CHAR(1) DEFAULT 'Y' NOT NULL,
    approval_status    VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    created_by         NUMBER(19),
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tax_rule PRIMARY KEY (tax_rule_id),
    CONSTRAINT uq_tax_rule_code UNIQUE (rule_code),
    CONSTRAINT fk_tax_rule_category FOREIGN KEY (tax_category_id) REFERENCES tax_category (tax_category_id),
    CONSTRAINT fk_tax_rule_creator FOREIGN KEY (created_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_tax_rule_type CHECK (tax_type IN ('VAT', 'PIT', 'CIT', 'OTHER')),
    CONSTRAINT ck_tax_rule_method CHECK (calculation_method IN ('EXCLUSIVE', 'INCLUSIVE', 'PROGRESSIVE', 'FIXED')),
    CONSTRAINT ck_tax_rule_rate CHECK (rate_percent >= 0),
    CONSTRAINT ck_tax_rule_dates CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_tax_rule_sim_only CHECK (simulation_only = 'Y'),
    CONSTRAINT ck_tax_rule_approval CHECK (approval_status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'RETIRED'))
);
CREATE INDEX ix_tax_rule_period ON tax_rule (tax_category_id, approval_status, valid_from, valid_to);

CREATE TABLE tax_invoice (
    tax_invoice_id     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    sales_order_id     NUMBER(19) NOT NULL,
    legal_entity_id    NUMBER(19) NOT NULL,
    invoice_code       VARCHAR2(50 CHAR) NOT NULL,
    idempotency_key    VARCHAR2(120 CHAR) NOT NULL,
    invoice_type       VARCHAR2(20 CHAR) DEFAULT 'SALES' NOT NULL,
    invoice_status     VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    simulation_only    CHAR(1) DEFAULT 'Y' NOT NULL,
    seller_name_snapshot VARCHAR2(300 CHAR) NOT NULL,
    seller_tax_id_snapshot VARCHAR2(30 CHAR),
    seller_address_snapshot VARCHAR2(1000 CHAR),
    buyer_name_snapshot VARCHAR2(200 CHAR),
    buyer_tax_id_snapshot VARCHAR2(30 CHAR),
    buyer_email_snapshot VARCHAR2(320 CHAR),
    buyer_address_snapshot VARCHAR2(1000 CHAR),
    subtotal_amount    NUMBER(18,2) NOT NULL,
    discount_amount    NUMBER(18,2) DEFAULT 0 NOT NULL,
    tax_amount         NUMBER(18,2) DEFAULT 0 NOT NULL,
    total_amount       NUMBER(18,2) NOT NULL,
    currency_code      CHAR(3) DEFAULT 'VND' NOT NULL,
    issued_at          TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    created_by         NUMBER(19),
    CONSTRAINT pk_tax_invoice PRIMARY KEY (tax_invoice_id),
    CONSTRAINT uq_tax_invoice_code UNIQUE (invoice_code),
    CONSTRAINT uq_tax_invoice_idem UNIQUE (idempotency_key),
    CONSTRAINT fk_tax_invoice_order FOREIGN KEY (sales_order_id) REFERENCES sales_order (sales_order_id),
    CONSTRAINT fk_tax_invoice_entity FOREIGN KEY (legal_entity_id) REFERENCES legal_entity (legal_entity_id),
    CONSTRAINT fk_tax_invoice_creator FOREIGN KEY (created_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_tax_invoice_type CHECK (invoice_type IN ('SALES', 'ADJUSTMENT', 'REPLACEMENT')),
    CONSTRAINT ck_tax_invoice_status CHECK (invoice_status IN ('DRAFT', 'PENDING', 'ACCEPTED', 'REJECTED', 'TIMEOUT', 'ADJUSTED', 'CANCELLED')),
    CONSTRAINT ck_tax_invoice_sim CHECK (simulation_only = 'Y'),
    CONSTRAINT ck_tax_invoice_amount CHECK (subtotal_amount >= 0 AND discount_amount >= 0 AND tax_amount >= 0 AND total_amount >= 0),
    CONSTRAINT ck_tax_invoice_currency CHECK (currency_code = 'VND')
);
CREATE INDEX ix_tax_invoice_order ON tax_invoice (sales_order_id, created_at);
CREATE INDEX ix_tax_invoice_status ON tax_invoice (invoice_status, created_at);

CREATE TABLE tax_invoice_line (
    tax_invoice_line_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tax_invoice_id      NUMBER(19) NOT NULL,
    order_line_id       NUMBER(19),
    line_no             NUMBER(6) NOT NULL,
    item_code_snapshot  VARCHAR2(80 CHAR),
    description_snapshot VARCHAR2(500 CHAR) NOT NULL,
    tax_category_code_snapshot VARCHAR2(40 CHAR) NOT NULL,
