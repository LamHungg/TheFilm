-- THEFILM Oracle schema - V001
-- Organization, identity references, cinema rooms, film catalog and screenings.
-- Flyway migration: execute once through the migration runner; do not run ad hoc
-- against a production schema without a reviewed backup and deployment plan.

CREATE TABLE org_chain (
    chain_id       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    chain_code     VARCHAR2(30 CHAR) NOT NULL,
    chain_name     VARCHAR2(200 CHAR) NOT NULL,
    status         VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_org_chain PRIMARY KEY (chain_id),
    CONSTRAINT uq_org_chain_code UNIQUE (chain_code),
    CONSTRAINT ck_org_chain_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE legal_entity (
    legal_entity_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    chain_id        NUMBER(19) NOT NULL,
    entity_code     VARCHAR2(30 CHAR) NOT NULL,
    legal_name      VARCHAR2(300 CHAR) NOT NULL,
    tax_identifier  VARCHAR2(30 CHAR),
    status          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_legal_entity PRIMARY KEY (legal_entity_id),
    CONSTRAINT uq_legal_entity_code UNIQUE (chain_id, entity_code),
    CONSTRAINT fk_legal_entity_chain FOREIGN KEY (chain_id) REFERENCES org_chain (chain_id),
    CONSTRAINT ck_legal_entity_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- Versioned seller/contact details preserve what was valid when a transaction occurred.
CREATE TABLE legal_entity_profile (
    entity_profile_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    legal_entity_id   NUMBER(19) NOT NULL,
    version_no        NUMBER(10) NOT NULL,
    valid_from        TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to          TIMESTAMP WITH TIME ZONE,
    display_name      VARCHAR2(300 CHAR) NOT NULL,
    tax_identifier    VARCHAR2(30 CHAR),
    registered_address VARCHAR2(1000 CHAR),
    invoice_email     VARCHAR2(320 CHAR),
    source_note       VARCHAR2(500 CHAR),
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_legal_entity_prof PRIMARY KEY (entity_profile_id),
    CONSTRAINT uq_entity_profile_ver UNIQUE (legal_entity_id, version_no),
    CONSTRAINT fk_entity_prof_entity FOREIGN KEY (legal_entity_id) REFERENCES legal_entity (legal_entity_id),
    CONSTRAINT ck_entity_prof_dates CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE TABLE cinema (
    cinema_id       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    chain_id        NUMBER(19) NOT NULL,
    legal_entity_id NUMBER(19) NOT NULL,
    cinema_code     VARCHAR2(30 CHAR) NOT NULL,
    cinema_name     VARCHAR2(200 CHAR) NOT NULL,
    address_line    VARCHAR2(1000 CHAR) NOT NULL,
    province_name   VARCHAR2(120 CHAR),
    district_name   VARCHAR2(120 CHAR),
    ward_name       VARCHAR2(120 CHAR),
    phone           VARCHAR2(30 CHAR),
    email           VARCHAR2(320 CHAR),
    time_zone       VARCHAR2(64 CHAR) DEFAULT 'Asia/Ho_Chi_Minh' NOT NULL,
    status          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cinema PRIMARY KEY (cinema_id),
    CONSTRAINT uq_cinema_code UNIQUE (chain_id, cinema_code),
    CONSTRAINT fk_cinema_chain FOREIGN KEY (chain_id) REFERENCES org_chain (chain_id),
    CONSTRAINT fk_cinema_entity FOREIGN KEY (legal_entity_id) REFERENCES legal_entity (legal_entity_id),
    CONSTRAINT ck_cinema_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'CLOSED'))
);

-- Keycloak is the identity provider. This table deliberately stores no password or credential hash.
CREATE TABLE app_user (
    app_user_id     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    oidc_issuer     VARCHAR2(500 CHAR) NOT NULL,
    oidc_subject    VARCHAR2(255 CHAR) NOT NULL,
    display_name    VARCHAR2(200 CHAR),
    email           VARCHAR2(320 CHAR),
    phone           VARCHAR2(30 CHAR),
    status          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (app_user_id),
    CONSTRAINT uq_app_user_oidc UNIQUE (oidc_issuer, oidc_subject),
    CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'ANONYMIZED'))
);

-- Data scope assignments complement authorization roles maintained in Keycloak.
CREATE TABLE user_cinema_scope (
    user_cinema_scope_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    app_user_id          NUMBER(19) NOT NULL,
    cinema_id            NUMBER(19) NOT NULL,
    valid_from           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    valid_to             TIMESTAMP WITH TIME ZONE,
    created_by           NUMBER(19),
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_user_cinema_scope PRIMARY KEY (user_cinema_scope_id),
    CONSTRAINT fk_user_scope_user FOREIGN KEY (app_user_id) REFERENCES app_user (app_user_id),
    CONSTRAINT fk_user_scope_cinema FOREIGN KEY (cinema_id) REFERENCES cinema (cinema_id),
    CONSTRAINT fk_user_scope_creator FOREIGN KEY (created_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_user_scope_dates CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE INDEX ix_user_scope_lookup ON user_cinema_scope (app_user_id, cinema_id, valid_to);

