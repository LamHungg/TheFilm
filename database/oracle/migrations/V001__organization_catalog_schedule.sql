CREATE TABLE screening (
    screening_id      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cinema_id         NUMBER(19) NOT NULL,
    room_id           NUMBER(19) NOT NULL,
    layout_id         NUMBER(19) NOT NULL,
    film_id           NUMBER(19) NOT NULL,
    film_version_id   NUMBER(19) NOT NULL,
    room_type_code_snapshot VARCHAR2(30 CHAR) NOT NULL,
    room_type_name_snapshot VARCHAR2(120 CHAR) NOT NULL,
    format_code       VARCHAR2(40 CHAR) NOT NULL,
    screening_type_code VARCHAR2(40 CHAR) NOT NULL,
    starts_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    cleanup_minutes   NUMBER(4) DEFAULT 0 NOT NULL,
    status            VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    created_by        NUMBER(19),
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_screening PRIMARY KEY (screening_id),
    CONSTRAINT fk_screening_cinema FOREIGN KEY (cinema_id) REFERENCES cinema (cinema_id),
    CONSTRAINT fk_screening_room FOREIGN KEY (room_id) REFERENCES cinema_room (room_id),
    CONSTRAINT fk_screening_layout FOREIGN KEY (layout_id) REFERENCES room_layout (layout_id),
    CONSTRAINT fk_screening_film FOREIGN KEY (film_id) REFERENCES film (film_id),
    CONSTRAINT fk_screening_version FOREIGN KEY (film_version_id) REFERENCES film_version (film_version_id),
    CONSTRAINT fk_screening_creator FOREIGN KEY (created_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_screening_dates CHECK (ends_at > starts_at),
    CONSTRAINT ck_screening_cleanup CHECK (cleanup_minutes >= 0),
    CONSTRAINT ck_screening_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'ON_SALE', 'CANCELLED', 'COMPLETED'))
);
CREATE INDEX ix_screening_cinema_start ON screening (cinema_id, starts_at, status);
CREATE INDEX ix_screening_room_time ON screening (room_id, starts_at, ends_at, status);
CREATE INDEX ix_screening_film_start ON screening (film_id, starts_at, status);

