CREATE TABLE film_review (
    film_review_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    film_id NUMBER NOT NULL,
    app_user_id NUMBER NOT NULL,
    score NUMBER(2) NOT NULL,
    review_title VARCHAR2(120 CHAR),
    review_text VARCHAR2(2000 CHAR) NOT NULL,
    tags VARCHAR2(500 CHAR),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_film_review PRIMARY KEY (film_review_id),
    CONSTRAINT fk_film_review_film FOREIGN KEY (film_id) REFERENCES film (film_id),
    CONSTRAINT fk_film_review_user FOREIGN KEY (app_user_id) REFERENCES app_user (app_user_id),
    CONSTRAINT uq_film_review_user UNIQUE (film_id, app_user_id),
    CONSTRAINT ck_film_review_score CHECK (score BETWEEN 1 AND 10)
);

CREATE INDEX ix_film_review_latest ON film_review (film_id, created_at DESC);
COMMENT ON TABLE film_review IS 'Đánh giá phim do tài khoản THEFILM đã mua vé gửi';
COMMENT ON COLUMN film_review.score IS 'Điểm khán giả THEFILM chấm từ 1 đến 10, độc lập với điểm nguồn ngoài';
