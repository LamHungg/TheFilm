    CONSTRAINT fk_order_line_show_seat FOREIGN KEY (show_seat_id) REFERENCES show_seat (show_seat_id),
    CONSTRAINT ck_order_line_type CHECK (item_type IN ('TICKET', 'FNB')),
    CONSTRAINT ck_order_line_shape CHECK (
        (item_type = 'TICKET' AND quantity = 1 AND screening_id IS NOT NULL AND show_seat_id IS NOT NULL AND fnb_product_id IS NULL)
        OR (item_type = 'FNB' AND screening_id IS NULL AND show_seat_id IS NULL)
