    ticket_change_request_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    request_number           VARCHAR2(40 CHAR) NOT NULL,
    source_ticket_id         NUMBER(19) NOT NULL,
    target_screening_id      NUMBER(19) NOT NULL,
    target_show_seat_id      NUMBER(19) NOT NULL,
    result_ticket_id         NUMBER(19),
    idempotency_key          VARCHAR2(120 CHAR) NOT NULL,
    reason                   VARCHAR2(1000 CHAR),
    price_difference         NUMBER(18,2) DEFAULT 0 NOT NULL,
    change_fee               NUMBER(18,2) DEFAULT 0 NOT NULL,
    request_status           VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    requested_by             NUMBER(19),
    reviewed_by              NUMBER(19),
    requested_at             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at             TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_ticket_change PRIMARY KEY (ticket_change_request_id),
    CONSTRAINT uq_ticket_change_no UNIQUE (request_number),
    CONSTRAINT uq_ticket_change_idem UNIQUE (idempotency_key),
    CONSTRAINT fk_change_source_ticket FOREIGN KEY (source_ticket_id) REFERENCES ticket (ticket_id),
    CONSTRAINT fk_change_target_screen FOREIGN KEY (target_screening_id) REFERENCES screening (screening_id),
    CONSTRAINT fk_change_target_seat FOREIGN KEY (target_show_seat_id) REFERENCES show_seat (show_seat_id),
    CONSTRAINT fk_change_result_ticket FOREIGN KEY (result_ticket_id) REFERENCES ticket (ticket_id),
    CONSTRAINT fk_change_requester FOREIGN KEY (requested_by) REFERENCES app_user (app_user_id),
    CONSTRAINT fk_change_reviewer FOREIGN KEY (reviewed_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_ticket_change_amount CHECK (change_fee >= 0),
    CONSTRAINT ck_ticket_change_status CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'PROCESSING', 'COMPLETED', 'FAILED', 'CANCELLED'))
);

CREATE TABLE refund_txn (
    refund_txn_id    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    refund_request_id NUMBER(19) NOT NULL,
    provider_ref     VARCHAR2(150 CHAR),
    idempotency_key  VARCHAR2(120 CHAR) NOT NULL,
    amount           NUMBER(18,2) NOT NULL,
    refund_status    VARCHAR2(20 CHAR) DEFAULT 'INITIATED' NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at     TIMESTAMP WITH TIME ZONE,
    provider_message VARCHAR2(1000 CHAR),
    CONSTRAINT pk_refund_txn PRIMARY KEY (refund_txn_id),
    CONSTRAINT uq_refund_idem UNIQUE (idempotency_key),
    CONSTRAINT fk_refund_txn_request FOREIGN KEY (refund_request_id) REFERENCES refund_request (refund_request_id),
    CONSTRAINT ck_refund_txn_amount CHECK (amount > 0),
    CONSTRAINT ck_refund_txn_status CHECK (refund_status IN ('INITIATED', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'TIMEOUT'))
);

