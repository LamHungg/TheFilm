    unit_price          NUMBER(18,2) NOT NULL,
    discount_amount     NUMBER(18,2) DEFAULT 0 NOT NULL,
    tax_category_code   VARCHAR2(40 CHAR),
    tax_rate_snapshot   NUMBER(7,4) DEFAULT 0 NOT NULL,
    tax_amount          NUMBER(18,2) DEFAULT 0 NOT NULL,
    line_total          NUMBER(18,2) NOT NULL,
    price_rule_code_snapshot VARCHAR2(40 CHAR),
    promotion_snapshot  VARCHAR2(500 CHAR),
