-- THEFILM Oracle schema - V002
-- Effective-dated pricing/promotions, membership, seat allocation, orders and money movement.

CREATE TABLE price_rule (
    price_rule_id      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    rule_code          VARCHAR2(40 CHAR) NOT NULL,
    cinema_id          NUMBER(19),
    room_type_id       NUMBER(19),
    seat_type_id       NUMBER(19),
    screening_type_code VARCHAR2(40 CHAR),
    weekday_no         NUMBER(1),
    valid_from         TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to           TIMESTAMP WITH TIME ZONE,
    base_price         NUMBER(18,2) NOT NULL,
    priority_no        NUMBER(6) DEFAULT 100 NOT NULL,
    approval_status    VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    created_by         NUMBER(19),
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_price_rule PRIMARY KEY (price_rule_id),
    CONSTRAINT uq_price_rule_code UNIQUE (rule_code),
    CONSTRAINT fk_price_rule_cinema FOREIGN KEY (cinema_id) REFERENCES cinema (cinema_id),
    CONSTRAINT fk_price_rule_room_type FOREIGN KEY (room_type_id) REFERENCES room_type (room_type_id),
    CONSTRAINT fk_price_rule_seat_type FOREIGN KEY (seat_type_id) REFERENCES seat_type (seat_type_id),
    CONSTRAINT fk_price_rule_creator FOREIGN KEY (created_by) REFERENCES app_user (app_user_id),
    CONSTRAINT ck_price_rule_weekday CHECK (weekday_no IS NULL OR weekday_no BETWEEN 1 AND 7),
    CONSTRAINT ck_price_rule_price CHECK (base_price >= 0),
    CONSTRAINT ck_price_rule_dates CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_price_rule_approval CHECK (approval_status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'RETIRED'))
);
CREATE INDEX ix_price_rule_match ON price_rule (approval_status, cinema_id, room_type_id, seat_type_id, valid_from, valid_to);

