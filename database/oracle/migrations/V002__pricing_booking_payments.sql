    order_line_id       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    sales_order_id      NUMBER(19) NOT NULL,
    line_no             NUMBER(6) NOT NULL,
    item_type           VARCHAR2(20 CHAR) NOT NULL,
