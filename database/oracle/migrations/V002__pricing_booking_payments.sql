-- One row per physical seat per screening is the serialization point for concurrent holds/sales.
-- Application service must lock the row (SELECT ... FOR UPDATE), re-check expiry/status, then mutate it.
CREATE TABLE show_seat (
    show_seat_id        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    screening_id        NUMBER(19) NOT NULL,
    room_seat_id        NUMBER(19) NOT NULL,
    seat_status         VARCHAR2(20 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
    current_order_id    NUMBER(19),
    hold_expires_at     TIMESTAMP WITH TIME ZONE,
    seat_code_snapshot  VARCHAR2(20 CHAR) NOT NULL,
    row_label_snapshot  VARCHAR2(10 CHAR) NOT NULL,
    seat_label_snapshot VARCHAR2(30 CHAR) NOT NULL,
    seat_type_code_snapshot VARCHAR2(30 CHAR) NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_show_seat PRIMARY KEY (show_seat_id),
    CONSTRAINT uq_show_seat UNIQUE (screening_id, room_seat_id),
    CONSTRAINT fk_show_seat_screening FOREIGN KEY (screening_id) REFERENCES screening (screening_id),
    CONSTRAINT fk_show_seat_room_seat FOREIGN KEY (room_seat_id) REFERENCES room_seat (room_seat_id),
    CONSTRAINT fk_show_seat_order FOREIGN KEY (current_order_id) REFERENCES sales_order (sales_order_id),
    CONSTRAINT ck_show_seat_status CHECK (seat_status IN ('AVAILABLE', 'HELD', 'SOLD', 'BLOCKED')),
    CONSTRAINT ck_show_seat_owner CHECK (
        (seat_status IN ('AVAILABLE', 'BLOCKED') AND current_order_id IS NULL AND hold_expires_at IS NULL)
        OR (seat_status = 'HELD' AND current_order_id IS NOT NULL AND hold_expires_at IS NOT NULL)
        OR (seat_status = 'SOLD' AND current_order_id IS NOT NULL AND hold_expires_at IS NULL)
    )
);
CREATE INDEX ix_show_seat_state ON show_seat (screening_id, seat_status, hold_expires_at);

