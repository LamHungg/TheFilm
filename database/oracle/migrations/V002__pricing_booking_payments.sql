    CONSTRAINT ck_order_line_qty CHECK (quantity > 0),
    CONSTRAINT ck_order_line_money CHECK (unit_price >= 0 AND discount_amount >= 0 AND tax_rate_snapshot >= 0 AND tax_amount >= 0 AND line_total >= 0)
