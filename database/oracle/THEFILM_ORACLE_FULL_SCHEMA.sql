CREATE TABLE org_chain (
    chain_id       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    chain_code     VARCHAR2(30 CHAR) NOT NULL,
    chain_name     VARCHAR2(200 CHAR) NOT NULL,
    status         VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_org_chain PRIMARY KEY (chain_id),
    CONSTRAINT uq_org_chain_code UNIQUE (chain_code),
    CONSTRAINT ck_org_chain_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
