CREATE TABLE seat_hold (
    seat_hold_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_seat_id BIGINT NOT NULL,
    sales_order_id BIGINT NOT NULL,
    held_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,
    hold_status VARCHAR(20) NOT NULL DEFAULT 'HELD',
    CONSTRAINT fk_seat_hold_seat FOREIGN KEY (show_seat_id) REFERENCES show_seat (show_seat_id),
    CONSTRAINT fk_seat_hold_order FOREIGN KEY (sales_order_id) REFERENCES sales_order (sales_order_id),
    CONSTRAINT ck_seat_hold_dates CHECK (expires_at > held_at)
