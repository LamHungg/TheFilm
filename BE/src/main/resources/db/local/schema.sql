-- Booking and pricing tables mirror the V002 Oracle model using H2-friendly types.
CREATE TABLE seat_type (
    seat_type_id BIGINT PRIMARY KEY,
    type_code VARCHAR(30) NOT NULL UNIQUE,
    type_name VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE room_seat (
    room_seat_id BIGINT PRIMARY KEY,
    room_id BIGINT NOT NULL,
    seat_type_id BIGINT NOT NULL,
    seat_code VARCHAR(20) NOT NULL,
    row_label VARCHAR(10) NOT NULL,
    seat_label VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uq_room_seat_code UNIQUE (room_id, seat_code),
    CONSTRAINT fk_room_seat_room FOREIGN KEY (room_id) REFERENCES cinema_room (room_id),
    CONSTRAINT fk_room_seat_type FOREIGN KEY (seat_type_id) REFERENCES seat_type (seat_type_id)
);

CREATE TABLE price_rule (
    price_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code VARCHAR(40) NOT NULL UNIQUE,
    cinema_id BIGINT,
    room_type_id BIGINT,
    seat_type_id BIGINT,
    screening_type_code VARCHAR(40),
    weekday_no INTEGER,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP WITH TIME ZONE,
    base_price DECIMAL(18,2) NOT NULL,
    priority_no INTEGER NOT NULL DEFAULT 100,
    approval_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_price_rule_cinema FOREIGN KEY (cinema_id) REFERENCES cinema (cinema_id),
    CONSTRAINT fk_price_rule_room_type FOREIGN KEY (room_type_id) REFERENCES room_type (room_type_id),
    CONSTRAINT fk_price_rule_seat_type FOREIGN KEY (seat_type_id) REFERENCES seat_type (seat_type_id),
    CONSTRAINT ck_price_rule_weekday CHECK (weekday_no IS NULL OR weekday_no BETWEEN 1 AND 7),
    CONSTRAINT ck_price_rule_price CHECK (base_price >= 0),
    CONSTRAINT ck_price_rule_dates CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE TABLE promo_campaign (
    promo_campaign_id BIGINT PRIMARY KEY,
    campaign_code VARCHAR(40) NOT NULL UNIQUE,
    campaign_name VARCHAR(200) NOT NULL,
    discount_type VARCHAR(20) NOT NULL,
    discount_value DECIMAL(18,4) NOT NULL,
    max_discount DECIMAL(18,2),
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP WITH TIME ZONE NOT NULL,
    stackable CHAR(1) NOT NULL DEFAULT 'N',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT ck_promo_discount_type CHECK (discount_type IN ('FIXED', 'PERCENT', 'POINTS')),
    CONSTRAINT ck_promo_valid_dates CHECK (valid_to > valid_from)
);

CREATE TABLE promo_voucher (
    voucher_id BIGINT PRIMARY KEY,
    promo_campaign_id BIGINT NOT NULL,
    voucher_code VARCHAR(80) NOT NULL UNIQUE,
    valid_from TIMESTAMP WITH TIME ZONE,
    valid_to TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_voucher_campaign FOREIGN KEY (promo_campaign_id) REFERENCES promo_campaign (promo_campaign_id),
    CONSTRAINT ck_voucher_valid_dates CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to > valid_from)
);

CREATE TABLE sales_order (
    sales_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    idempotency_key VARCHAR(120),
    order_type VARCHAR(20) NOT NULL,
    sales_channel VARCHAR(20) NOT NULL,
    cinema_id BIGINT NOT NULL,
    legal_entity_id BIGINT NOT NULL,
    app_user_id BIGINT,
    member_account_id BIGINT,
    guest_name VARCHAR(200),
    guest_email VARCHAR(320),
    guest_phone VARCHAR(30),
    currency_code CHAR(3) NOT NULL DEFAULT 'VND',
    subtotal_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    order_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    expires_at TIMESTAMP WITH TIME ZONE,
    paid_at TIMESTAMP WITH TIME ZONE,
    issued_at TIMESTAMP WITH TIME ZONE,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sales_order_idem UNIQUE (sales_channel, idempotency_key),
    CONSTRAINT fk_order_cinema FOREIGN KEY (cinema_id) REFERENCES cinema (cinema_id),
    CONSTRAINT ck_order_type CHECK (order_type IN ('TICKET', 'FNB', 'COMBINED')),
    CONSTRAINT ck_order_channel CHECK (sales_channel IN ('ONLINE', 'BOX', 'KIOSK', 'ADMIN')),
    CONSTRAINT ck_order_amounts CHECK (subtotal_amount >= 0 AND discount_amount >= 0 AND tax_amount >= 0 AND total_amount >= 0)
);

CREATE TABLE sales_order_line (
    order_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL,
    line_no INTEGER NOT NULL,
    item_type VARCHAR(20) NOT NULL,
    screening_id BIGINT,
    show_seat_id BIGINT,
    fnb_product_id BIGINT,
    product_name_snapshot VARCHAR(300) NOT NULL,
    product_code_snapshot VARCHAR(80),
    screening_type_snapshot VARCHAR(40),
    room_type_snapshot VARCHAR(120),
    seat_type_snapshot VARCHAR(120),
    seat_code_snapshot VARCHAR(20),
    unit_price DECIMAL(18,2) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    tax_category_code VARCHAR(40),
    tax_rate_snapshot DECIMAL(7,4) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    line_total DECIMAL(18,2) NOT NULL,
    price_rule_code_snapshot VARCHAR(40),
    promotion_snapshot VARCHAR(500),
    line_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_order_line_no UNIQUE (sales_order_id, line_no),
    CONSTRAINT fk_order_line_order FOREIGN KEY (sales_order_id) REFERENCES sales_order (sales_order_id),
    CONSTRAINT fk_order_line_screening FOREIGN KEY (screening_id) REFERENCES screening (screening_id),
    CONSTRAINT fk_order_line_seat FOREIGN KEY (show_seat_id) REFERENCES show_seat (show_seat_id),
    CONSTRAINT ck_order_line_amount CHECK (unit_price >= 0 AND quantity > 0 AND discount_amount >= 0 AND line_total >= 0)
