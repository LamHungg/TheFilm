package vn.thefilm.backend.controller;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.time.OffsetDateTime;
import java.util.Arrays;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.context.SecurityContext;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RestController;

import vn.thefilm.backend.dto.AssignCinemaScopeRequest;
import vn.thefilm.backend.dto.LinkEmployeeUserRequest;
import vn.thefilm.backend.exception.GlobalExceptionHandler;
import vn.thefilm.backend.security.CinemaScopeAspect;
import vn.thefilm.backend.security.CinemaScopeValidator;
import vn.thefilm.backend.security.RequireCinemaScope;
import vn.thefilm.backend.security.TheFilmUserPrincipal;
import vn.thefilm.backend.service.CinemaScopeService;
import vn.thefilm.backend.repository.AppUserRepository;
import vn.thefilm.backend.repository.EmployeeRepository;

@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:thefilmadminemployeetest;DB_CLOSE_DELAY=-1;MODE=Oracle",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.flyway.enabled=false",
        "spring.jpa.hibernate.ddl-auto=none",
        "spring.sql.init.mode=always",
        "spring.sql.init.schema-locations=classpath:db/admin-fixture/schema.sql",
        "spring.sql.init.data-locations=classpath:db/admin-fixture/data.sql"
})
@Transactional
class AdminEmployeeControllerTests {

    private static final String OIDC_ISSUER = "https://identity.thefilm.test/realms/thefilm";

    @Autowired private AdminEmployeeController controller;
    @Autowired private AppUserRepository appUserRepository;
    @Autowired private EmployeeRepository employeeRepository;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private CinemaScopeService cinemaScopeService;
    @Autowired private CinemaScopeValidator cinemaScopeValidator;
    @Autowired private CinemaScopeAspect cinemaScopeAspect;

    @BeforeEach
    void resetAppUserIdentity() {
        jdbcTemplate.execute(
                "ALTER TABLE app_user ALTER COLUMN app_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)");
    }

    @AfterEach
    void clearSecurityContext() {
        SecurityContextHolder.clearContext();
    }

    @Test
    void permitsChainAdminAndHrAndDeniesOtherRoles() {
        authenticate(2L, "ROLE_CHAIN_ADMIN");
        assertThat(controller.searchEmployees(null, null).success()).isTrue();

        authenticate(2L, "ROLE_HR");
        assertThat(controller.searchEmployees(null, null).success()).isTrue();

        authenticate(1L, "ROLE_CUSTOMER");
        assertThatThrownBy(() -> controller.searchEmployees(null, null))
                .isInstanceOf(AccessDeniedException.class);
    }

    @Test
    void deniesCustomerAccessToEmployeeLinkingAndCinemaScopeAdministration() {
        authenticate(1L, "ROLE_CUSTOMER");
        OffsetDateTime validFrom = OffsetDateTime.now().minusMinutes(1);

        assertThatThrownBy(() -> controller.linkUser(1L,
                new LinkEmployeeUserRequest(OIDC_ISSUER, "unauthorized-link-subject", "customer@example.test"),
                principal(1L), "unauthorized-link-test", new MockHttpServletRequest()))
                .isInstanceOf(AccessDeniedException.class);
        assertThatThrownBy(() -> controller.assignCinemaScope(1L,
                new AssignCinemaScopeRequest(1L, validFrom, validFrom.plusDays(1)),
                principal(1L), "unauthorized-scope-test", new MockHttpServletRequest()))
                .isInstanceOf(AccessDeniedException.class);
    }

    @Test
    void linksEmployeeToAccountUsingOidcIssuerAndSubject() {
        long employeeId = createUnlinkedEmployee();
        String subject = "employee-link-subject-test";
        authenticate(2L, "ROLE_HR");

        var response = controller.linkUser(employeeId,
                new LinkEmployeeUserRequest(OIDC_ISSUER, subject, "new.employee@example.test"),
                principal(2L), "link-test-request", new MockHttpServletRequest());

        assertThat(response.success()).isTrue();
        assertThat(response.data().employeeId()).isEqualTo(employeeId);
        assertThat(response.data().appUserId()).isNotNull();
        var linkedUser = appUserRepository.findByOidcIssuerAndOidcSubject(OIDC_ISSUER, subject).orElseThrow();
        assertThat(linkedUser.getAppUserId()).isEqualTo(response.data().appUserId());
        assertThat(employeeRepository.findById(employeeId).orElseThrow().getAppUser().getAppUserId())
                .isEqualTo(linkedUser.getAppUserId());
    }

    @Test
    void assignsValidCinemaScopeToLinkedEmployeeAccount() {
        OffsetDateTime validFrom = OffsetDateTime.now().minusMinutes(1);
        OffsetDateTime validTo = validFrom.plusDays(30);
        authenticate(2L, "ROLE_CHAIN_ADMIN");

        var response = controller.assignCinemaScope(1L,
                new AssignCinemaScopeRequest(2L, validFrom, validTo),
                principal(2L), "scope-test-request", new MockHttpServletRequest());

        assertThat(response.success()).isTrue();
        assertThat(cinemaScopeService.hasEffectiveCinemaScope(2L, 2L)).isTrue();
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM user_cinema_scope WHERE app_user_id = ? AND cinema_id = ?",
                Integer.class, 2L, 2L)).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT created_by FROM user_cinema_scope WHERE app_user_id = ? AND cinema_id = ?",
                Long.class, 2L, 2L)).isEqualTo(2L);
    }

    @Test
    void validatorAndAspectRejectCinemaOutsideTheUsersEffectiveScope() throws Exception {
        authenticate(2L, "ROLE_HR");
        Authentication authentication = SecurityContextHolder.getContext().getAuthentication();

        cinemaScopeValidator.requireAccess(authentication, 1L);
        assertThatThrownBy(() -> cinemaScopeValidator.requireAccess(authentication, 2L))
                .isInstanceOf(AccessDeniedException.class);

        ProxyFactory proxyFactory = new ProxyFactory(new ScopedProbeImplementation());
        proxyFactory.setProxyTargetClass(true);
        proxyFactory.addAdvisor(cinemaScopeAspect);
        ScopedProbeImplementation scopedProbe = (ScopedProbeImplementation) proxyFactory.getProxy();

        assertThat(scopedProbe.readCinema(1L)).isEqualTo(1L);
        assertThatThrownBy(() -> scopedProbe.readCinema(2L))
                .isInstanceOf(AccessDeniedException.class);

        MockMvc scopedMvc = MockMvcBuilders.standaloneSetup(scopedProbe)
                .setControllerAdvice(new GlobalExceptionHandler())
                .build();
        scopedMvc.perform(get("/test/cinemas/{cinemaId}", 1L))
                .andExpect(status().isOk());
        scopedMvc.perform(get("/test/cinemas/{cinemaId}", 2L))
                .andExpect(status().isForbidden());
    }

    private long createUnlinkedEmployee() {
        jdbcTemplate.update("""
                INSERT INTO employee
                    (employee_id, chain_id, app_user_id, employee_code, full_name, email, status, hired_on)
                VALUES (9001, 1, NULL, 'TF-TEST-LINK-9001', 'Test Linked Employee',
                        'test.link@example.test', 'PENDING', CURRENT_DATE)
                """);
        return 9001L;
    }

    private static TheFilmUserPrincipal principal(Long appUserId) {
        return new TheFilmUserPrincipal("test-subject-" + appUserId, OIDC_ISSUER,
                "test@example.test", "test-user", "Test User", appUserId);
    }

    private static void authenticate(Long appUserId, String... roles) {
        var authorities = Arrays.stream(roles).map(SimpleGrantedAuthority::new).toList();
        Authentication authentication = new UsernamePasswordAuthenticationToken(
                principal(appUserId), "test-credentials", authorities);
        SecurityContext context = SecurityContextHolder.createEmptyContext();
        context.setAuthentication(authentication);
        SecurityContextHolder.setContext(context);
    }

    @RestController
    static class ScopedProbeImplementation {
        @GetMapping("/test/cinemas/{cinemaId}")
        @RequireCinemaScope("cinemaId")
        public Long readCinema(@PathVariable("cinemaId") Long cinemaId) {
            return cinemaId;
        }
    }
}
