package vn.thefilm.backend.controller;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.web.FilterChainProxy;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.context.WebApplicationContext;

import vn.thefilm.backend.dto.LoginRequest;
import vn.thefilm.backend.dto.RegisterRequest;

@SpringBootTest(properties = {
        "spring.profiles.active=local",
        "spring.datasource.url=jdbc:h2:mem:thefilmauthtest;DB_CLOSE_DELAY=-1;MODE=Oracle",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.flyway.enabled=false",
        "spring.jpa.hibernate.ddl-auto=none",
        "spring.sql.init.mode=always",
        "spring.sql.init.schema-locations=classpath:db/local/schema.sql",
        "spring.sql.init.data-locations=classpath:db/local/data.sql"
})
@Transactional
class AuthControllerTests {

    @Autowired private WebApplicationContext context;
    @Autowired private FilterChainProxy springSecurityFilterChain;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private ObjectMapper objectMapper;

    private MockMvc mvc;

    @BeforeEach
    void setUp() {
        jdbcTemplate.execute(
                "ALTER TABLE app_user ALTER COLUMN app_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000)");
        mvc = MockMvcBuilders.webAppContextSetup(context)
                .addFilters(springSecurityFilterChain)
                .build();
    }

    @AfterEach
    void tearDown() {
        SecurityContextHolder.clearContext();
    }

    @Test
    void registerAndLoginFlowSucceeds() throws Exception {
        RegisterRequest registerReq = new RegisterRequest(
                "testnewuser@thefilm.vn",
                "Secret123!",
                "Người Dùng Thử Nghiệm",
                "0987654321");

        MvcResult regResult = mvc.perform(post("/api/v1/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(registerReq)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.accessToken").isString())
                .andExpect(jsonPath("$.data.user.email").value("testnewuser@thefilm.vn"))
                .andExpect(jsonPath("$.data.user.displayName").value("Người Dùng Thử Nghiệm"))
                .andReturn();

        JsonNode regJson = objectMapper.readTree(regResult.getResponse().getContentAsString());
        String initialToken = regJson.path("data").path("accessToken").asText();
        assertThat(initialToken).isNotBlank();

        // Login with correct credentials
        LoginRequest loginReq = new LoginRequest(
                "testnewuser@thefilm.vn",
                "Secret123!");

        MvcResult loginResult = mvc.perform(post("/api/v1/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(loginReq)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.accessToken").isString())
                .andExpect(jsonPath("$.data.user.email").value("testnewuser@thefilm.vn"))
                .andReturn();

        JsonNode loginJson = objectMapper.readTree(loginResult.getResponse().getContentAsString());
        String loginToken = loginJson.path("data").path("accessToken").asText();
        assertThat(loginToken).isNotBlank();

        // Call /api/v1/auth/me with Bearer token
        mvc.perform(get("/api/v1/auth/me")
                        .header("Authorization", "Bearer " + loginToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.email").value("testnewuser@thefilm.vn"))
                .andExpect(jsonPath("$.data.displayName").value("Người Dùng Thử Nghiệm"));
    }

    @Test
    void registerRejectsDuplicateEmail() throws Exception {
        RegisterRequest registerReq = new RegisterRequest(
                "duplicate@thefilm.vn",
                "Secret123!",
                "User First",
                null);

        mvc.perform(post("/api/v1/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(registerReq)))
                .andExpect(status().isOk());

        RegisterRequest dupReq = new RegisterRequest(
                "DUPLICATE@thefilm.vn",
                "AnotherPassword123!",
                "User Second",
                null);

        mvc.perform(post("/api/v1/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(dupReq)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.success").value(false));
    }

    @Test
    void loginRejectsWrongPasswordOrMissingUser() throws Exception {
        LoginRequest wrongPass = new LoginRequest(
                "an.nguyen@example.com",
                "WrongPassword");

        mvc.perform(post("/api/v1/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(wrongPass)))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.success").value(false));

        LoginRequest notFound = new LoginRequest(
                "nobody@example.com",
                "Password123!");

        mvc.perform(post("/api/v1/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(notFound)))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.success").value(false));
    }
}
