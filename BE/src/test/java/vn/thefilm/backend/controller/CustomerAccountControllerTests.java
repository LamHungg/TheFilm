@SpringBootTest(properties = {
        "spring.profiles.active=local",
        "spring.datasource.url=jdbc:h2:mem:thefilmcustomeraccounttest;DB_CLOSE_DELAY=-1;MODE=Oracle",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.flyway.enabled=false",
        "spring.jpa.hibernate.ddl-auto=none",
        "spring.sql.init.mode=always",
        "spring.sql.init.schema-locations=classpath:db/local/schema.sql",
        "spring.sql.init.data-locations=classpath:db/local/data.sql"
})
@Transactional
class CustomerAccountControllerTests {

    private static final String API = "/api/v1/customer";
    private static final String ISSUER = "https://identity.example.test/realms/thefilm";

    @Autowired private WebApplicationContext context;
    @Autowired private CustomerAccountService customerAccountService;
    @Autowired private CustomerConsentRepository customerConsentRepository;
    @Autowired private SalesOrderRepository salesOrderRepository;
    @Autowired private ShowSeatRepository showSeatRepository;
    @Autowired private TicketRepository ticketRepository;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private EntityManager entityManager;

    private MockMvc mvc;

    @BeforeEach
    void setUp() {
        jdbcTemplate.execute(
                "ALTER TABLE app_user ALTER COLUMN app_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)");
        mvc = MockMvcBuilders.webAppContextSetup(context).build();
    }

    @AfterEach
    void clearSecurityContext() {
        SecurityContextHolder.clearContext();
    }

    @Test
    void getProfileSynchronizesCustomerFromAuthenticatedOidcSubject() throws Exception {
        TheFilmUserPrincipal principal = principal("profile-subject", "profile@example.test", "Profile Customer");

        mvc.perform(get(API + "/profile").with(authenticatedAs(principal)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.email").value("profile@example.test"))
                .andExpect(jsonPath("$.data.displayName").value("Profile Customer"))
                .andExpect(jsonPath("$.data.preferredLocale").value("vi-VN"));

        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM app_user WHERE oidc_issuer = ? AND oidc_subject = ? AND email = ?",
                Integer.class, ISSUER, "profile-subject", "profile@example.test")).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM customer_profile p JOIN app_user u ON u.app_user_id = p.app_user_id "
                        + "WHERE u.oidc_issuer = ? AND u.oidc_subject = ?",
                Integer.class, ISSUER, "profile-subject")).isEqualTo(1);
    }

    @Test
    void putProfileUpdatesCustomerFields() throws Exception {
        TheFilmUserPrincipal principal = principal("update-subject", "update@example.test", "JWT Name");
        LocalDate dateOfBirth = LocalDate.of(1995, 4, 12);

        mvc.perform(put(API + "/profile").with(authenticatedAs(principal))
                        .contentType("application/json")
                        .content("{\"displayName\":\"Updated Customer\",\"preferredCinemaId\":2,"
                                + "\"dateOfBirth\":\"1995-04-12\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.displayName").value("Updated Customer"))
                .andExpect(jsonPath("$.data.preferredCinemaId").value(2))
                .andExpect(jsonPath("$.data.dateOfBirth").value(dateOfBirth.toString()));

        Long appUserId = jdbcTemplate.queryForObject(
                "SELECT app_user_id FROM app_user WHERE oidc_issuer = ? AND oidc_subject = ?",
                Long.class, ISSUER, "update-subject");
        assertThat(jdbcTemplate.queryForObject("SELECT display_name FROM app_user WHERE app_user_id = ?",
                String.class, appUserId)).isEqualTo("Updated Customer");
        assertThat(jdbcTemplate.queryForObject("SELECT preferred_cinema_id FROM customer_profile WHERE app_user_id = ?",
                Long.class, appUserId)).isEqualTo(2L);
        assertThat(jdbcTemplate.queryForObject("SELECT date_of_birth FROM customer_profile WHERE app_user_id = ?",
                java.sql.Date.class, appUserId).toLocalDate()).isEqualTo(dateOfBirth);
    }

    @Test
    void postConsentPersistsPolicyChoiceForAuthenticatedCustomer() throws Exception {
        TheFilmUserPrincipal principal = principal("consent-subject", "consent@example.test", "Consent Customer");

        mvc.perform(post(API + "/consent").with(authenticatedAs(principal))
                        .contentType("application/json")
                        .content("{\"consentType\":\"terms_of_service\",\"policyVersion\":\"2026-11\","
                                + "\"consentStatus\":\"accepted\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data").value("OK"));

        CustomerProfileDto customer = customerAccountService.syncOrGetCustomer(
                ISSUER, "consent-subject", "consent@example.test", "Consent Customer");
        assertThat(customerConsentRepository.findByAppUser_AppUserIdAndConsentTypeOrderByCapturedAtDesc(
                customer.appUserId(), CustomerConsentType.TERMS))
                .singleElement()
                .satisfies(consent -> {
                    assertThat(consent.getPolicyVersion()).isEqualTo("2026-11");
                    assertThat(consent.getConsentStatus().name()).isEqualTo("GRANTED");
                    assertThat(consent.getCapturedChannel()).isEqualTo("CUSTOMER_PORTAL");
                });
    }

    @Test
    void customerCannotReadAnotherCustomersOrderOrTickets() throws Exception {
        CustomerProfileDto customerB = customerAccountService.syncOrGetCustomer(
                ISSUER, "customer-b-subject", "customer-b@example.test", "Customer B");
        String orderCode = "AUTH-" + UUID.randomUUID().toString().replace("-", "").substring(0, 16);
        SalesOrderEntity order = salesOrderRepository.saveAndFlush(new SalesOrderEntity(orderCode,
                "auth-test-" + UUID.randomUUID(), 1L, 1L, "Customer B", "customer-b@example.test", null,
                BigDecimal.valueOf(75000), BigDecimal.ZERO, BigDecimal.ZERO, BigDecimal.valueOf(75000),
                OffsetDateTime.now().plusMinutes(10)));
        jdbcTemplate.update("UPDATE sales_order SET app_user_id = ? WHERE sales_order_id = ?",
                customerB.appUserId(), order.getSalesOrderId());

        ShowSeatEntity seat = showSeatRepository.findById(1L).orElseThrow();
        SalesOrderLineEntity line = new SalesOrderLineEntity(order, 1, seat.getScreening(), seat,
                "Tầng Mây Cuối Cùng", "2D", "Standard", "STANDARD", BigDecimal.valueOf(75000),
                BigDecimal.ZERO, BigDecimal.ZERO, BigDecimal.valueOf(75000));
        entityManager.persist(line);
        entityManager.flush();
        String ticketNumber = "AUTH-TICKET-" + UUID.randomUUID();
        ticketRepository.saveAndFlush(new TicketEntity(line, ticketNumber,
                UUID.randomUUID().toString().replace("-", ""), "Tầng Mây Cuối Cùng", "THEFILM Nguyễn Trãi",
                "Phòng 01", seat.getScreening().getStartsAt(), seat.getSeatLabelSnapshot()));

        TheFilmUserPrincipal customerBPrincipal = new TheFilmUserPrincipal("customer-b-subject", ISSUER,
                "customer-b@example.test", "customer-b-subject", "Customer B", customerB.appUserId());
        mvc.perform(get("/api/v1/public/bookings/orders/{code}", orderCode)
                        .with(authenticatedAs(customerBPrincipal)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.orderCode").value(orderCode));
        mvc.perform(get("/api/v1/public/bookings/orders/{code}/tickets", orderCode)
                        .with(authenticatedAs(customerBPrincipal)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data[0].ticketNumber").value(ticketNumber));

        TheFilmUserPrincipal customerA = principal("customer-a-subject", "customer-a@example.test", "Customer A");
        mvc.perform(get("/api/v1/public/bookings/orders/{code}", orderCode).with(authenticatedAs(customerA)))
                .andExpect(status().isNotFound());
        mvc.perform(get("/api/v1/public/bookings/orders/{code}/tickets", orderCode).with(authenticatedAs(customerA)))
                .andExpect(status().isNotFound());
    }

    private TheFilmUserPrincipal principal(String subject, String email, String displayName) {
        return new TheFilmUserPrincipal(subject, ISSUER, email, subject, displayName, null);
    }

    private RequestPostProcessor authenticatedAs(TheFilmUserPrincipal principal) {
        return request -> {
            Jwt jwt = Jwt.withTokenValue("customer-test-token")
                    .header("alg", "none")
                    .issuer(principal.oidcIssuer())
                    .subject(principal.oidcSubject())
                    .issuedAt(Instant.now())
                    .expiresAt(Instant.now().plusSeconds(300))
                    .claim("email", principal.email())
                    .build();
            JwtAuthenticationToken authentication = new JwtAuthenticationToken(
                    jwt, List.of(new SimpleGrantedAuthority("ROLE_CUSTOMER")), principal.oidcSubject()) {
                @Override
                public Object getPrincipal() {
                    return principal;
                }
            };
            SecurityContext securityContext = SecurityContextHolder.createEmptyContext();
            securityContext.setAuthentication(authentication);
            SecurityContextHolder.setContext(securityContext);
            request.setUserPrincipal(authentication);
            return request;
        };
    }
}
