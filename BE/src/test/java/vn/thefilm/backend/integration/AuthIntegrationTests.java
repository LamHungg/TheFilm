@ActiveProfiles("oracle")
@Import(AuthIntegrationTests.TestJwtConfiguration.class)
class AuthIntegrationTests {

    private static final String ISSUER = "https://identity.thefilm.local/realms/thefilm";
    private static final String CUSTOMER_API = "/api/v1/customer";
    private static final String ADMIN_API = "/api/v1/admin/employees";
    private static final SecretKey TEST_SIGNING_KEY = new SecretKeySpec(
            "THEFILM-local-auth-integration-key".getBytes(StandardCharsets.UTF_8), "HmacSHA256");

    @Autowired private WebApplicationContext context;
    @Autowired private FilterChainProxy springSecurityFilterChain;
    @Autowired private JdbcTemplate jdbcTemplate;
    @Autowired private AuditLogService auditLogService;

    private final ObjectMapper objectMapper = new ObjectMapper().findAndRegisterModules();

    private MockMvc mvc;

    @BeforeEach
    void setUpMockMvc() {
        jdbcTemplate.execute(
                "ALTER TABLE app_user ALTER COLUMN app_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)");
        mvc = MockMvcBuilders.webAppContextSetup(context).addFilters(springSecurityFilterChain).build();
    }

    @Test
    void rejectsForgedAndExpiredTokensWithUnauthorizedResponse() throws Exception {
        String validToken = token("invalid-token-case", "invalid-token@example.test", "Invalid Token", List.of("CUSTOMER"));
        String[] jwtParts = validToken.split("\\.");
        String alteredSignature = (jwtParts[2].charAt(0) == 'A' ? "B" : "A") + jwtParts[2].substring(1);
        String forgedToken = jwtParts[0] + "." + jwtParts[1] + "." + alteredSignature;
        String expiredToken = token("expired-token-case", "expired-token@example.test", "Expired Token",
                List.of("CUSTOMER"), Instant.now().minusSeconds(60));

        mvc.perform(get(CUSTOMER_API + "/profile").header("Authorization", "Bearer " + forgedToken))
                .andExpect(status().isUnauthorized());
        mvc.perform(get(CUSTOMER_API + "/profile").header("Authorization", "Bearer " + expiredToken))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void customerAuthenticationAuthorizationAndAuditRedactionWorkEndToEnd() throws Exception {
        String runId = UUID.randomUUID().toString();
        String customerSub = "auth-customer-" + runId;
        String customerEmail = "auth-customer-" + runId + "@example.test";
        String customerName = "Auth Customer " + runId.substring(0, 8);
        String customerToken = token(customerSub, customerEmail, customerName, List.of("CUSTOMER"));

        MvcResult firstLogin = mvc.perform(get(CUSTOMER_API + "/profile")
                        .header("Authorization", "Bearer " + customerToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.email").value(customerEmail))
                .andExpect(jsonPath("$.data.displayName").value(customerName))
                .andReturn();
        JsonNode firstProfile = objectMapper.readTree(firstLogin.getResponse().getContentAsString()).path("data");
        long customerId = firstProfile.path("appUserId").asLong();
        assertThat(customerId).isPositive();
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM customer_profile WHERE app_user_id = ?", Integer.class, customerId)).isEqualTo(1);

        String refreshedName = customerName + " Updated";
        String loginAgainToken = token(customerSub, customerEmail, refreshedName, List.of("CUSTOMER"));
        mvc.perform(get(CUSTOMER_API + "/profile")
                        .header("Authorization", "Bearer " + loginAgainToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.appUserId").value(customerId))
                .andExpect(jsonPath("$.data.displayName").value(refreshedName));
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM app_user WHERE oidc_issuer = ? AND oidc_subject = ?",
                Integer.class, ISSUER, customerSub)).isEqualTo(1);

        mvc.perform(put(CUSTOMER_API + "/profile")
                        .header("Authorization", "Bearer " + loginAgainToken)
                        .contentType("application/json")
                        .content("{\"displayName\":\"Profile Updated\",\"preferredCinemaId\":1,\"dateOfBirth\":\"1990-01-01\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.displayName").value("Profile Updated"))
                .andExpect(jsonPath("$.data.preferredCinemaId").value(1));

        mvc.perform(post(CUSTOMER_API + "/consent")
                        .header("Authorization", "Bearer " + loginAgainToken)
                        .contentType("application/json")
                        .content("{\"consentType\":\"MARKETING\",\"policyVersion\":\"auth-test-v1\",\"consentStatus\":\"ACCEPTED\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data").value("OK"));
        assertThat(jdbcTemplate.queryForObject("""
                SELECT COUNT(*) FROM customer_consent
                WHERE app_user_id = ? AND consent_type = 'MARKETING'
                  AND policy_version = 'auth-test-v1' AND consent_status = 'GRANTED'
                  AND captured_channel = 'CUSTOMER_PORTAL'
                """, Integer.class, customerId)).isEqualTo(1);

        mvc.perform(get(ADMIN_API).header("Authorization", "Bearer " + loginAgainToken))
                .andExpect(status().isForbidden());

        String employeeCode = "AUTH-" + runId.substring(0, 8);
        jdbcTemplate.update("""
                INSERT INTO employee (chain_id, employee_code, full_name, email, status, hired_on)
                VALUES (1, ?, 'Auth Integration Employee', ?, 'PENDING', CURRENT_DATE)
                """, employeeCode, "employee-" + runId + "@example.test");
        long employeeId = jdbcTemplate.queryForObject(
                "SELECT employee_id FROM employee WHERE employee_code = ?", Long.class, employeeCode);

        String hrToken = token("employee-demo-001", "quocbao@example.test", "Trần Quốc Bảo", List.of("HR"));
        mvc.perform(get(ADMIN_API).header("Authorization", "Bearer " + hrToken))
                .andExpect(status().isOk());
        String linkedEmployeeSub = "auth-employee-" + runId;
        mvc.perform(post(ADMIN_API + "/" + employeeId + "/link-user")
                        .header("Authorization", "Bearer " + hrToken)
                        .header("X-Request-Id", "auth-link-" + runId)
                        .contentType("application/json")
                        .content("{\"oidcIssuer\":\"" + ISSUER + "\",\"oidcSubject\":\"" + linkedEmployeeSub
                                + "\",\"email\":\"employee-" + runId + "@example.test\"}"))
                .andExpect(status().isOk());

        String validFrom = OffsetDateTime.now().minusDays(1).withNano(0).toString();
        mvc.perform(post(ADMIN_API + "/" + employeeId + "/scopes")
                        .header("Authorization", "Bearer " + hrToken)
                        .header("X-Request-Id", "auth-scope-" + runId)
                        .contentType("application/json")
                        .content("{\"cinemaId\":1,\"validFrom\":\"" + validFrom + "\"}"))
                .andExpect(status().isOk());
        assertThat(jdbcTemplate.queryForObject("""
                SELECT COUNT(*) FROM user_cinema_scope s
                JOIN app_user u ON u.app_user_id = s.app_user_id
                WHERE u.oidc_issuer = ? AND u.oidc_subject = ? AND s.cinema_id = 1
                """, Integer.class, ISSUER, linkedEmployeeSub)).isEqualTo(1);

        String chainAdminToken = token(customerSub, customerEmail, refreshedName, List.of("CHAIN_ADMIN"));
        mvc.perform(get(ADMIN_API).header("Authorization", "Bearer " + chainAdminToken))
                .andExpect(status().isOk());

        String passwordMarker = "AUTH_TEST_PASSWORD_MARKER_" + runId;
        String secretMarker = "AUTH_TEST_CLIENT_SECRET_" + runId;
        auditLogService.recordSecurityEvent(customerId, "AUTH_INTEGRATION_REDACTION_TEST", "AUTH_TEST", runId,
                "auth-audit-" + runId,
                Map.of("password", passwordMarker, "client_secret", secretMarker),
                Map.of("details", "Bearer " + customerToken, "raw_token", customerToken), "127.0.0.1");

        List<Map<String, Object>> auditRows = jdbcTemplate.queryForList("""
                SELECT action_code, object_type, object_id, trace_id, before_data, after_data, source_ip
                FROM audit_event
                """);
        assertThat(auditRows).isNotEmpty();
        String serializedAuditRows = objectMapper.writeValueAsString(auditRows);
        assertThat(serializedAuditRows)
                .doesNotContain(passwordMarker)
                .doesNotContain(secretMarker)
                .doesNotContain(customerToken)
                .doesNotContain("raw_token=");
        assertThat(serializedAuditRows).contains("[REDACTED]");
    }

    private String token(String subject, String email, String name, List<String> roles) {
        Instant now = Instant.now();
        return token(subject, email, name, roles, now.plusSeconds(300));
    }

    private String token(String subject, String email, String name, List<String> roles, Instant expiresAt) {
        Instant now = Instant.now();
        Instant issuedAt = expiresAt.isBefore(now)
                ? expiresAt.minusSeconds(5)
                : now.minusSeconds(5);
        JwtClaimsSet claims = JwtClaimsSet.builder()
                .issuer(ISSUER)
                .subject(subject)
                .issuedAt(issuedAt)
                .expiresAt(expiresAt)
                .claim("email", email)
                .claim("name", name)
                .claim("preferred_username", subject)
                .claim("realm_access", Map.of("roles", roles))
                .build();
        return new NimbusJwtEncoder(new ImmutableSecret<>(TEST_SIGNING_KEY))
                .encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims))
                .getTokenValue();
    }

    @TestConfiguration(proxyBeanMethods = false)
    static class TestJwtConfiguration {

        @Bean
        JwtDecoder testJwtDecoder() {
            return NimbusJwtDecoder.withSecretKey(TEST_SIGNING_KEY)
                    .macAlgorithm(MacAlgorithm.HS256)
                    .build();
        }
    }
}
